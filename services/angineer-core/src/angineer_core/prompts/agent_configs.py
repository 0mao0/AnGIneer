    "\n\n## 末尾追问规则\n"
    "1. 给出最终回答时，在回答末尾追加一个与答案相关的邀请式问句"
    "（仅一句话，不加导语，直接以问句结尾），询问用户是否想了解某个后续方向，"
    "例如\"您是否想知道…？\"\"需要我展开讲讲…吗？\"；"
